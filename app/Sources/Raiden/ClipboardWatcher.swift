import AppKit
import ApplicationServices
import Carbon
import RaidenCore

/// クリップボードを見張って文字のコピーを覚え、⌘V で貼った先も覚える。履歴から選んだ物を前のアプリに貼る。
///
///   コピーは 0.5 秒ごとに changeCount を見る（NSPasteboard に通知は無い）。コピー元はその時に前面にあるアプリと窓の名前。
///   パスワード管理アプリなどが付ける「覚えないで」の印（org.nspasteboard.ConcealedType など）の付いた物は覚えない。
///   貼った先は ⌘V を押した時に前面にあるアプリと窓の名前（キーを見るのでアクセシビリティの許可が要る。無ければ Raiden から貼った分だけ）。
///   窓の名前もアクセシビリティの許可が無ければ空になる。
final class ClipboardWatcher {
    private let store: Store
    private var keep: () -> Int
    private var timer: Timer?
    private var lastChange: Int
    /// 今クリップボードにある物の id（⌘V を押した時に貼った先を付ける相手）
    private(set) var currentID: Int64?
    private var keyMonitor: Any?
    private let work = DispatchQueue(label: "raiden.clipboard", qos: .utility)

    /// 覚えない印（nspasteboard.org の決まり）と、パスワード管理アプリの印
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                         "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
                                         "Pasteboard generator type", "net.antelle.keeweb"]

    init(store: Store, keep: @escaping () -> Int) {
        self.store = store
        self.keep = keep
        lastChange = NSPasteboard.general.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
        startKeyMonitor()
        rlog("クリップボードの見張りを開始")
    }

    func stop() {
        timer?.invalidate(); timer = nil
        if let m = keyMonitor { NSEvent.removeMonitor(m); keyMonitor = nil }
        currentID = nil
    }

    /// ⌘V を見る口（アクセシビリティの許可があれば付く。許可が後から来たら次に開いた時に付け直す）
    func startKeyMonitor() {
        guard keyMonitor == nil, timer != nil, AXIsProcessTrusted() else { return }
        keyMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { [weak self] e in
            let mods = e.modifierFlags.intersection(.deviceIndependentFlagsMask)
            guard e.keyCode == UInt16(kVK_ANSI_V), mods.contains(.command), !mods.contains(.control) else { return }
            self?.notePaste()
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Self.skipTypes) { currentID = nil; return }
        guard let text = pb.string(forType: .string) else { currentID = nil; return }
        let src = Self.frontPlace()
        // Raiden 自身が書いた物（履歴から選んだ物）は pasteFromHistory で扱う
        if src.bundleID == Bundle.main.bundleIdentifier { return }
        let n = keep()
        work.async { [weak self] in
            guard let self else { return }
            let id = self.store.addClip(text, source: src, keep: n)
            DispatchQueue.main.async { if self.lastChange == c { self.currentID = id } }
        }
    }

    private func notePaste() {
        guard let id = currentID, NSPasteboard.general.changeCount == lastChange else { return }
        let p = Self.frontPlace()
        work.async { [weak self] in self?.store.recordPaste(clip: id, to: p) }
    }

    /// 履歴から選んだ物をクリップボードに置き、paste なら前のアプリに ⌘V を送る（パネルを閉じた後に呼ぶ）
    func use(_ item: ClipItem, paste: Bool, target: NSRunningApplication?) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        currentID = item.id
        work.async { [weak self] in self?.store.touchClip(item.id) }
        guard paste else { return }
        guard AXIsProcessTrusted() else {
            // 許可を頼む（一度だけシステムの案内が出る）。今回はコピーだけ
            let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(opts)
            rlog("アクセシビリティの許可が無いので貼り付けずにコピーだけ")
            return
        }
        // 前のアプリに戻し、前面に来るのを少し待ってから送る
        target?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in
            let p = Self.frontPlace()
            Self.sendCommandV()
            self?.work.async { self?.store.recordPaste(clip: item.id, to: p) }
        }
    }

    static func sendCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// 前面のアプリと、その窓の名前（アクセシビリティの許可が無ければ空）
    static func frontPlace() -> ClipItem.Place {
        let app = NSWorkspace.shared.frontmostApplication
        var title = ""
        if let pid = app?.processIdentifier, AXIsProcessTrusted() {
            let ax = AXUIElementCreateApplication(pid)
            var win: CFTypeRef?
            if AXUIElementCopyAttributeValue(ax, kAXFocusedWindowAttribute as CFString, &win) == .success, let w = win {
                var t: CFTypeRef?
                if AXUIElementCopyAttributeValue(w as! AXUIElement, kAXTitleAttribute as CFString, &t) == .success {
                    title = (t as? String) ?? ""
                }
            }
        }
        return .init(bundleID: app?.bundleIdentifier ?? "", app: app?.localizedName ?? "", title: title, at: Date())
    }
}
